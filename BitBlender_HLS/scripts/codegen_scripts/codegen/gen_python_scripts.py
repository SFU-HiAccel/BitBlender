        codeArr.append('' + "\n")
        codeArr.append('This script demonstrates how to optimize a simple vector addition design in' + "\n")
        codeArr.append('a Vitis object file. In this example, the object file is generated from the' + "\n")
        codeArr.append('TAPA compiler. However, by modifying "RadipStreamTAPA" to "RapidStreamVitis",' + "\n")
        codeArr.append('this script can be used to optimize a design in the standard Vitis flow.' + "\n")
        codeArr.append('"""' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('__copyright__ = """' + "\n")
        codeArr.append('Copyright (c) 2024 RapidStream Design Automation, Inc. and contributors.  All rights reserved.' + "\n")
        codeArr.append('The contributor(s) of this file has/have agreed to the RapidStream Contributor License Agreement.' + "\n")
        codeArr.append('"""' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('from rapidstream import get_u280_vitis_device_factory, RapidStreamTAPA' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('# Replace with RapidStreamVitis for the  ".xo" files generated by `v++`.' + "\n")
        codeArr.append('# Create a RapidStream project in the "run" directory:' + "\n")
        codeArr.append('rs = RapidStreamTAPA("rapidstream_build")' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('# Use the "xilinx_u280_gen3x16_xdma_1_202211_1" platform as the device:' + "\n")
        codeArr.append('u280_factory = get_u280_vitis_device_factory("xilinx_u280_gen3x16_xdma_1_202211_1")' + "\n")

        codeArr.append('# Reserve resources for the HBM Memory Sub-System.' + "\n")
        codeArr.append('# The HMSS is not part of the user kernel so the partition optimization process' + "\n")
        codeArr.append('# is unaware of its existence. We need to manually reserve resources for it.' + "\n")
        codeArr.append('# For 512-bit HBM channels, each HBM channel uses approximately the following resources:' + "\n")
        codeArr.append('# AREA_PER_HBM_CHANNEL = {' + "\n")
        codeArr.append('#     "LUT": 5000,' + "\n")
        codeArr.append('#     "FF": 6500,' + "\n")
        codeArr.append('#     "BRAM": 0,' + "\n")
        codeArr.append('#     "URAM": 0,' + "\n")
        codeArr.append('#     "DSP": 0,' + "\n")
        codeArr.append('# }' + "\n")
        codeArr.append('u280_factory.reduce_slot_area(1, 0, lut=5000 * 1, ff=6500 * 1)' + "\n")
        codeArr.append('u280_factory.reduce_slot_area(0, 0, lut=5000 * 2, ff=6500 * 2)' + "\n")
        codeArr.append('rs.set_virtual_device(u280_factory.generate_virtual_device())' + "\n")

        codeArr.append('' + "\n")
        codeArr.append('# Add the design object file (".xo") to the project:' + "\n")
        codeArr.append('rs.add_xo_file("./_x.hw_multistream_BitBlender.xilinx_u280_gen3x16_xdma_1_202211_1/multistream_BitBlender.xo")' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('# Specify the Vitis platform and connectivity configuration:' + "\n")
        codeArr.append('rs.set_vitis_platform("xilinx_u280_gen3x16_xdma_1_202211_1")' + "\n")
        codeArr.append('rs.set_vitis_connectivity_config("./src/BitBlender.ini")' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('# Set the clock target for the design:' + "\n")
        codeArr.append('rs.add_clock("ap_clk", period_ns={})'.format(self.config.target_clkT_ns) + "\n")
        codeArr.append('' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('########################' + "\n")
        codeArr.append('### BINDING INPUT PORTS' + "\n")
        codeArr.append('########################' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('LEFT_HBM_SLOT = "SLOT_X0Y0:SLOT_X0Y0"' + "\n")
        codeArr.append('RIGHT_HBM_SLOT = "SLOT_X1Y0:SLOT_X1Y0"' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('# Bind input ports to LHS :' + "\n")
        codeArr.append('left_ports = [' + "\n")
        codeArr.append('    "input_bv",'+ "\n")
        codeArr.append('    "key_in"'+ "\n")
        codeArr.append(']' + "\n")
        codeArr.append('for p in left_ports:' + "\n")
        codeArr.append('    rs.assign_port_to_region("m_axi_{p}_.*".format(p=p), "SLOT_X0Y0:SLOT_X0Y0")' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('# Bind output ports to RHS :' + "\n")
        codeArr.append('right_ports = [' + "\n")
        codeArr.append('    "out_bits"'+ "\n")
        codeArr.append(']' + "\n")
        codeArr.append('for p in right_ports:' + "\n")
        codeArr.append('    rs.assign_port_to_region("m_axi_{p}_.*".format(p=p), "SLOT_X1Y0:SLOT_X1Y0")' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('# All ports must be assigned, according to the rapidstream-cookbook' + "\n")
        codeArr.append('#   (https://github.com/rapidstream-org/rapidstream-cookbook/blob/main/benchmarks/sextans_sparse_matrix_multiplication/run.py)' + "\n")
        codeArr.append('rs.assign_port_to_region("s_axi_control_.*", left_slot)' + "\n")
        codeArr.append('rs.assign_port_to_region("ap_clk", left_slot)' + "\n")
        codeArr.append('rs.assign_port_to_region("ap_rst_n", left_slot)' + "\n")
        codeArr.append('rs.assign_port_to_region("interrupt", left_slot)' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('##### # Force some cells to be placed in a specific region:' + "\n")
        codeArr.append('##### #rs.assign_cell_to_region("a", "SLOT_X0Y1:SLOT_X0Y1")' + "\n")
        codeArr.append('' + "\n")
        codeArr.append('# Start the RapidStream optimization process:' + "\n")
        codeArr.append('rs.run_dse(' + "\n")
        codeArr.append('    max_workers=2' + "\n")
        codeArr.append('    ,max_dse_limit=0.85' + "\n")
        codeArr.append('    ,min_dse_limit=0.4' + "\n")
        codeArr.append(')' + "\n")
        return codeArr




